/* Writes js/menu-media.js: product slug -> photo path, for every product in
   server/data/products.json (menu items from assets/img/items/, drinks from
   the photos already used by js/cocktails.js).   node media.mjs */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(fileURLToPath(new URL("../..", import.meta.url)));
const products = JSON.parse(fs.readFileSync(path.join(root, "server/data/products.json"), "utf8"));
const slugify = (v) => v.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "").replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");

const drinks = {};
const src = fs.readFileSync(path.join(root, "js/cocktails.js"), "utf8");
for (const line of src.slice(src.indexOf("var DATA = {"), src.indexOf("/* ---------- render ---------- */")).split("\n")) {
  const name = line.match(/\bn:\s*"([^"]*)"/)?.[1];
  const photo = line.match(/\b(?:photo|cover):\s*"([^"]*)"/)?.[1];
  const price = line.match(/\bp:\s*"([^"]*)"/)?.[1] || "";
  if (!name || !photo) continue;
  const base = slugify(`cocktail-${name}`);
  if (price.includes("/")) { drinks[`${base}-piccola`] = photo; drinks[`${base}-grande`] = photo; }
  else drinks[base] = photo;
}

const media = {};
const missing = [];
for (const { slug } of products) {
  const own = `assets/img/items/${slug}.webp`;
  const photo = fs.existsSync(path.join(root, own)) ? own : drinks[slug];
  if (!photo) missing.push(slug);
  media[slug] = photo || null;
}
const body = JSON.stringify(media, null, 1).replace(/\n\s*/g, "\n  ");
fs.writeFileSync(path.join(root, "js/menu-media.js"),
  `/* Generated by tools/models/media.mjs — product slug -> photo. 3D models live in assets/models/<slug>.glb|.usdz */\nwindow.IL_CHIOSCO_MEDIA = ${body};\n`);
console.log(`menu-media.js: ${products.length} products${missing.length ? `, no photo: ${missing.join(", ")}` : ""}`);
